export const STYLE_CATEGORIES = GROUPS.map(([name]) => name)
export const INTUITIVE_STYLES = GROUPS.flatMap(([category, color, entries]) =>
  entries.map(([id, name_zh, name_en, desc]) => ({
    id, name_zh, name_en, desc, category, color,
    image: `/style-previews/v2/${id}.webp`,
  })),
)

export function filterStyles({ query = '', category = '', selectedOnly = false, selectedIds = [] } = {}) {
  const term = query.trim().toLocaleLowerCase()
  const chosen = new Set(selectedIds)
  return INTUITIVE_STYLES.filter(style =>
    (!category || style.category === category) &&
    (!selectedOnly || chosen.has(style.id)) &&
    (!term || `${style.name_zh} ${style.name_en} ${style.desc} ${style.category}`.toLocaleLowerCase().includes(term)),
  )
}
